    private Localization() {
    }

    public static boolean isEnglish() {
        return english;
    }

    public static void toggleLanguage() {
        english = !english;
    }

    public static String languageButtonText() {
        return english ? "Tiếng Việt" : "English";
    }

    public static String text(String vietnamese) {
        if (!english) {
            return vietnamese;
        }
        String translated = ENGLISH.get(vietnamese);
        if (translated != null) {
            return translated;
        }
        return translateQuantity(vietnamese);
    }

    public static ModuleDefinition localize(ModuleDefinition module) {
        String title = english ? switch (module.id()) {
            case "UC-09" -> "Suppliers";
            case "UC-12" -> "Goods Receiving";
            case "UC-13" -> "Storage Locations";
            default -> text(module.title());
        } : module.title();
        return new ModuleDefinition(
                module.id(),
                title,
                text(module.group()),
                text(module.description()),
                text(module.actionLabel()),
                translate(module.columns()),
                translate(module.formFields()),
                module.report(),
                module.staffAccessible());
    }

    private static List<String> translate(List<String> values) {
        return values.stream().map(Localization::text).toList();
    }

    private static String translateQuantity(String value) {
        String[][] units = {
                {" sản phẩm", " products"},
                {" mặt hàng", " items"},
                {" nhân viên", " staff"},
                {" hóa đơn", " invoices"},
                {" đơn vị", " units"},
                {" hộp", " boxes"},
                {" chai", " bottles"},
                {" giờ", " hours"},
                {" phút", " minutes"},
                {" điểm", " points"},
                {" dòng", " rows"}
        };
        for (String[] unit : units) {
            if (value.endsWith(unit[0])) {
                String quantity = value.substring(0, value.length() - unit[0].length()).trim();
                if (quantity.matches("[+\\-0-9.,]+")) {
                    return quantity + unit[1];
                }
            }
        }
        return value;
    }

    private static void add(String... translations) {
        if (translations.length % 2 != 0) {
            throw new IllegalArgumentException("Translations must be provided as source/target pairs.");
        }
        for (int index = 0; index < translations.length; index += 2) {
            ENGLISH.put(translations[index], translations[index + 1]);
        }
    }
